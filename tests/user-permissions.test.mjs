import { readFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
import { test } from 'node:test'
import { PGlite } from '@electric-sql/pglite'

const ids = {
    admin: '00000000-0000-4000-8000-000000000001',
    userA: '00000000-0000-4000-8000-000000000002',
    userB: '00000000-0000-4000-8000-000000000003',
    admin2: '00000000-0000-4000-8000-000000000004'
}

const db = new PGlite()
await db.exec(`
create role anon nologin;
create role authenticated nologin;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
grant usage on schema public, auth to anon, authenticated;
grant execute on function auth.uid() to anon, authenticated;
create table auth.users(id uuid primary key, email text, created_at timestamptz not null default now());
create table public.profiles(id uuid primary key references auth.users(id) on delete cascade, email text, role text default 'user' check(role in ('user','admin')));
create table public.links(id bigint generated by default as identity primary key, user_id uuid references auth.users(id), user_email text, slug text not null unique, original_url text, created_at timestamptz default now());
create table public.settings(key text primary key, value jsonb);
alter table public.links enable row level security;
create policy own_read on public.links for select to authenticated using (auth.uid() = user_id);
create policy own_insert on public.links for insert to authenticated with check (auth.uid() = user_id);
create policy own_delete on public.links for delete to authenticated using (auth.uid() = user_id);
grant select, insert, update, delete on public.links, public.settings to authenticated;
grant usage on all sequences in schema public to authenticated;
-- Deliberately broad historical policies must not defeat new restrictive boundaries.
create policy historical_open on public.links for all to authenticated using (true) with check (true);
alter table public.settings enable row level security;
create policy historical_settings on public.settings for all to authenticated using (true) with check (true);
`)
